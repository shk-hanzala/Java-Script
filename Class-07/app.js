let count = 10;
//Post increament
console.log(count++);
console.log(count);    //Output = 10

//Post decreament
console.log(count--);
console.log(count);    //Output = 11

//Pre increament
console.log(++count);
console.log(count);    //Output = 11

//Pre decreament
console.log(--count);
console.log(count);    //Output = 10

