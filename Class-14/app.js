// 1. toUpperCase()
let name = "muhammad hassan";

console.log(name.toUpperCase());      // Output: MUHAMMAD HASSAN


// 2. toLowerCase()
let city = "KARACHI";

console.log(city.toLowerCase());      // Output: karachi


// 3. slice()
let message = "JavaScript is easy";

console.log(message.slice(0, 10));    // Output: JavaScript


// 4. Array
let fruits = ["Apple", "Banana", "Mango", "Orange"];

console.log(fruits);


// 5. Using all methods on one variable
let text = "JavaScript Programming";

console.log(text.toUpperCase());     // Output: JAVASCRIPT PROGRAMMING

console.log(text.toLowerCase());     // Output: javascript programming

console.log(text.slice(0, 10));      // Output: JavaScript